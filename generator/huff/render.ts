// Writers for the generated Huff files and the Foundry test of a t != 4
// permutation. A permutation that does not fit the fork's code size is cut
// into parts (Part<i>.huff): each part is a contract that takes the state as
// calldata, and every part but the last STATICCALLs the next one with the
// state in memory and returns what it returns. The next part's address is
// the 32-byte word the deployer appends to the initcode; CONSTRUCTOR keeps
// it behind the runtime code, where NEXT_PART() reads it with CODECOPY.

import { hex, PRIME } from "../field.ts";
import type { Params } from "../params.ts";
import {
  dupText,
  pushBytes,
  pushGas,
  pushText,
  GAS,
  type Emitter,
} from "./emitter.ts";
import { DEFAULT_HARDFORK, FORKS, type Fork } from "./fork.ts";
import {
  describeOptions,
  type BuildOptions,
  type BuildResult,
} from "./schedule.ts";

const HEADER = `// This file is generated by generator/huff/generate.ts. Do not edit manually.
// Security: https://github.com/zemse/poseidon2-evm/blob/main/SECURITY.md
`;

// ---- paths -----------------------------------------------------------------

// src/bn254/huff for the default fork, src/bn254/huff/<fork> otherwise
export function huffDir(fork: Fork): string {
  return fork.name === DEFAULT_HARDFORK
    ? "src/bn254/huff"
    : `src/bn254/huff/${fork.name}`;
}

export function testDir(fork: Fork): string {
  return fork.name === DEFAULT_HARDFORK ? "test" : `test/${fork.name}`;
}

// the foundry-huff name of a contract in the width directory
export function huffName(fork: Fork, t: number, file: string): string {
  const dir = huffDir(fork).slice("src/".length);
  return `${dir}/t${t}/${file}`;
}

// includes of a permutation in the width directory
function includes(fork: Fork, utilsPath: string): string {
  let text = `#include "${utilsPath}"\n`;
  if (fork.reach > 16) text += `#include "../Eip8024.huff"\n`;
  if (!fork.push0) text += `#include "../Zero.huff"\n`;
  return text;
}

function forkNote(fork: Fork): string {
  if (fork.reach > 16) {
    return `/// @dev Uses EIP-8024 DUPN / SWAPN (Eip8024.huff): runs on Amsterdam and later only\n`;
  }
  if (!fork.push0) {
    return `/// @dev No PUSH0 (Zero.huff): runs before Shanghai as well\n`;
  }
  return "";
}

// ---- straight-line code outside the macro ----------------------------------

// Lines with their gas and bytes, for the entry and the hand-off.
class Code {
  lines: string[] = [];
  gas = 0;
  bytes = 0;
  private pending: string[] = [];
  readonly fork: Fork;

  constructor(fork: Fork) {
    this.fork = fork;
  }

  op(text: string, gas: number, bytes: number) {
    this.pending.push(text);
    this.gas += gas;
    this.bytes += bytes;
  }

  push(c: number) {
    const v = BigInt(c);
    this.op(
      pushText(v, this.fork),
      pushGas(v, this.fork),
      pushBytes(v, this.fork),
    );
  }

  dup(n: number) {
    this.op(dupText(n), GAS.dup, n <= 16 ? 1 : 2);
  }

  end(comment = "") {
    const ops = `    ${this.pending.join(" ")}`;
    this.pending = [];
    this.lines.push(comment ? `${ops.padEnd(40)} // ${comment}` : ops);
  }

  blank() {
    this.lines.push("");
  }

  text(line: string) {
    this.lines.push(line);
  }
}

// t calldata words reduced mod PRIME onto the stack, shadowed inputs also
// stored to their slot
function loads(code: Code, t: number, inputSlots: (number | undefined)[]) {
  code.op("SETUP()", GAS.push, 33);
  code.end("[PRIME]");
  for (let i = t - 1; i >= 0; i--) {
    // PRIME sits under the words loaded so far, pushed again once out of
    // reach (same gas, 33 bytes)
    if (t - i <= code.fork.reach) code.dup(t - i);
    else code.op("[PRIME]", GAS.push, 33);
    code.push(32 * i);
    code.op("calldataload", 3, 1);
    code.op("mod", GAS.mod, 1);
    const slot = inputSlots[i];
    if (slot !== undefined) {
      code.dup(1);
      code.push(slot);
      code.op("mstore", GAS.mstore, 1);
    }
    const stack = Array.from({ length: t - i }, (_, k) => `s${i + k}`);
    code.end(`[${stack.join(", ")}, PRIME]`);
  }
}

// return t words: from the stack top (in state order) or from memory [0, 32t)
function ret(code: Code, t: number, fromMemory: boolean) {
  if (!fromMemory) {
    for (let i = 0; i < t; i++) {
      code.push(32 * i);
      code.op("mstore", GAS.mstore, 1);
      code.end();
    }
  }
  code.push(32 * t);
  code.push(0);
  code.op("return", 0, 1);
  code.end();
}

// STATICCALL the next part with the state at [0, 32t) and return its output
function handOver(code: Code, t: number, part: number) {
  code.text(`    // forward the state to part ${part + 1} and return its output`);
  code.push(32 * t);
  code.push(0);
  code.push(32 * t);
  code.push(0);
  code.op("NEXT_PART()", nextPartGas(t), nextPartBytes(t));
  code.op("gas", 2, 1);
  code.op("staticcall", code.fork.coldAccount, 1);
  code.end("[success]");
  code.op("returndatasize", 2, 1);
  code.push(32 * t);
  code.op("eq", 3, 1);
  code.op("and", 3, 1);
  code.op("ok", 3, 3);
  code.op("jumpi", 10, 1);
  code.end();
  code.push(0);
  code.push(0);
  code.op("revert", 0, 1);
  code.end();
  code.op("ok:", 1, 1);
  code.end();
  ret(code, t, true);
}

// 0x20 0x20 codesize sub <32t> codecopy <32t> mload
function nextPartGas(t: number): number {
  const off = BigInt(32 * t);
  const fork = FORKS.shanghai;
  return 3 + 3 + 2 + 3 + pushGas(off, fork) + 6 + pushGas(off, fork) + 3;
}

function nextPartBytes(t: number): number {
  const off = BigInt(32 * t);
  const fork = FORKS.shanghai;
  return 2 + 2 + 1 + 1 + pushBytes(off, fork) + 1 + pushBytes(off, fork) + 1;
}

// Gas and bytes of a part's code around the permutation macro: the entry
// (calldata loads) and the tail (return or hand-over, the hand-over with the
// cold STATICCALL but without the callee).
export type Overhead = { entryGas: number; tailGas: number; bytes: number };

export function overhead(
  fork: Fork,
  t: number,
  inputSlots: (number | undefined)[],
  stateInMemory: boolean,
  handsOver: boolean,
): Overhead {
  const entry = new Code(fork);
  loads(entry, t, inputSlots);
  const tail = new Code(fork);
  if (handsOver) handOver(tail, t, 0);
  else ret(tail, t, stateInMemory);
  return {
    entryGas: entry.gas,
    tailGas: tail.gas,
    bytes: entry.bytes + tail.bytes,
  };
}

// Memory expansion gas of a frame that touches [0, bytes).
export function memoryGas(bytes: number): number {
  const words = Math.ceil(bytes / 32);
  return 3 * words + Math.floor((words * words) / 512);
}

// Runtime bytes of the entry contract around a permutation (loads, return).
export function entryBytes(
  fork: Fork,
  t: number,
  inputSlots: (number | undefined)[] = [],
  stateInMemory = false,
): number {
  return overhead(fork, t, inputSlots, stateInMemory, false).bytes;
}

// ---- files -----------------------------------------------------------------

export function renderPermutation(
  params: Params,
  result: BuildResult,
  opts: BuildOptions,
  utilsPath: string,
  fork: Fork = FORKS.shanghai,
): string {
  const { t, roundsF, roundsP } = params;
  const outputs = Array.from({ length: t }, (_, i) => `s${i}'`).join(", ");
  const inputs = Array.from({ length: t }, (_, i) => `s${i}`).join(", ");
  const layout = result.stateInMemory
    ? `the state in memory at [0, ${hexOff(32 * t)}) with clean outputs (stack: garbage)`
    : t <= 4
      ? `[${outputs}, PRIME, ...garbage...] with clean outputs`
      : `[${outputs}, ...garbage...] with clean outputs`;
  return `${HEADER}
${includes(fork, utilsPath)}
/// @notice Poseidon2 permutation for BN254 with t = ${t}, Rf = ${roundsF}, Rp = ${roundsP}
/// @dev takes [${inputs}, PRIME] with clean inputs, returns ${layout}
/// @dev Every ADD / MUL below was checked by the generator's bound tracker to fit in uint256
${forkNote(fork)}${stats(result.emitter, result)}
/// @dev schedule options: ${describeOptions(opts)}
#define macro POSEIDON2_PERMUTATION() = {
${result.lines.join("\n")}
}
`;
}

function stats(e: Emitter, result: BuildResult): string {
  let text = `/// @dev ${result.gas} gas, max stack depth ${result.maxDepth}, max dup ${result.maxDup}, ${result.bytes} bytes`;
  if (e.stores > 0 || e.loads > 0) {
    text += `, ${e.stores} values shadowed in memory, ${e.loads} loads`;
  }
  return text;
}

function hexOff(n: number): string {
  return "0x" + n.toString(16);
}

// DUP17() .. DUP235() and SWAP17() .. SWAP235() as the raw EIP-8024 bytes,
// since neither huffc nor huff-neo knows the mnemonics. The immediate x
// encodes n = (x + 145) % 256.
export function renderEip8024(reach: number): string {
  const macros: string[] = [];
  for (const [name, opcode] of [
    ["DUP", 0xe6],
    ["SWAP", 0xe7],
  ] as const) {
    for (let n = 17; n <= reach; n++) {
      const imm = (n - 145) & 0xff;
      const bytes = `0x${opcode.toString(16)}${imm.toString(16).padStart(2, "0")}`;
      macros.push(
        `#define macro ${name}${n}() = { __VERBATIM(${bytes}) }`.padEnd(52) +
          `// ${name.toLowerCase()}n ${n}`,
      );
    }
  }
  return `${HEADER}
/// @notice EIP-8024 DUPN / SWAPN (Amsterdam) for stack slots 17 to ${reach}
/// @dev DUPn() copies the n-th item, SWAPn() swaps the top with the (n + 1)-th item, 3 gas and 2 bytes each
${macros.join("\n")}
`;
}

// PUSH1 0x00 for the forks before Shanghai: huffc turns every zero literal
// into PUSH0 (EIP-3855), which they do not have.
// next to the Part<i>.huff files of a split width
export function renderDeployParts(): string {
  return `// SPDX-License-Identifier: MIT
${HEADER}pragma solidity ^0.8.13;

/// @notice Deploys the parts of a split Huff permutation (generator/huff/split.ts)
/// @dev Parts go up last to first: each initcode but the last gets the address
/// of the part after it appended as a 32-byte word, which that part's
/// constructor keeps behind its runtime code. The address returned is part 0,
/// the contract that takes the t input words and returns the t output words.
library DeployParts {
    function deploy(bytes[] memory initcodes) internal returns (address first) {
        address next;
        for (uint256 i = initcodes.length; i > 0; i--) {
            bytes memory code =
                i == initcodes.length ? initcodes[i - 1] : bytes.concat(initcodes[i - 1], abi.encode(next));
            assembly {
                next := create(0, add(code, 0x20), mload(code))
            }
            require(next != address(0), "part deployment failed");
        }
        return next;
    }
}
`;
}

export function renderZero(): string {
  return `${HEADER}
/// @notice A zero as PUSH1 0x00 (3 gas, 2 bytes) for the forks without EIP-3855 PUSH0, which huffc emits for any zero literal
#define macro ZERO() = { __VERBATIM(0x6000) }
`;
}

// Minimal entry contract for t != 4: calldata holds t words which are reduced
// mod PRIME, the permuted state is returned as t words.
export function renderEntry(
  params: Params,
  fork: Fork = FORKS.shanghai,
  result?: BuildResult,
): string {
  const { t } = params;
  const code = new Code(fork);
  loads(code, t, result?.inputSlots ?? []);
  code.blank();
  const inMemory = result?.stateInMemory ?? false;
  code.op("POSEIDON2_PERMUTATION()", 0, 0);
  code.end(
    inMemory
      ? `state at memory [0, ${hexOff(32 * t)})`
      : `[s0', ..., s${t - 1}', ...]`,
  );
  code.blank();
  ret(code, t, inMemory);
  return `${HEADER}
#include "./Permutation.huff"

/// @notice Poseidon2 permutation entry for t = ${t}: calldata = ${t} words (reduced mod PRIME), returns ${t} words
#define macro MAIN() = {
${code.lines.join("\n")}
}
`;
}

// Part `part` of `count` of a split permutation: the rounds of its range,
// the entry, and the hand-over to the next part or the return.
export function renderPart(
  params: Params,
  result: BuildResult,
  opts: BuildOptions,
  utilsPath: string,
  fork: Fork,
  part: number,
  count: number,
): string {
  const { t, roundsF, roundsP } = params;
  const { from, to } = result.range;
  const inputs = Array.from({ length: t }, (_, i) => `s${i}`).join(", ");
  const last = part === count - 1;
  const steps =
    from === 0
      ? `the initial linear layer and rounds 0 to ${to - 2}`
      : `rounds ${from - 1} to ${to - 2}`;
  const code = new Code(fork);
  loads(code, t, result.inputSlots);
  code.blank();
  code.op("POSEIDON2_PART()", 0, 0);
  code.end(`state at memory [0, ${hexOff(32 * t)})`);
  code.blank();
  if (last) ret(code, t, true);
  else handOver(code, t, part);
  const next = new Code(fork);
  next.op("0x20 0x20 codesize sub", 0, 0);
  next.push(32 * t);
  next.op("codecopy", 0, 0);
  next.end(`memory[${hexOff(32 * t)}] = address word`);
  next.push(32 * t);
  next.op("mload", 0, 0);
  next.end("[next]");
  const ctor = new Code(fork);
  ctor.op("__codesize(CONSTRUCTOR)", 0, 0);
  ctor.end("[c]");
  ctor.op("dup1 codesize sub", 0, 0);
  ctor.end("[len, c]");
  ctor.op("dup1 swap2", 0, 0);
  ctor.push(0);
  ctor.op("codecopy", 0, 0);
  ctor.end("[len]");
  ctor.push(0);
  ctor.op("return", 0, 0);
  ctor.end();
  const chain = last
    ? ""
    : `
/// @notice Address of part ${part + 1}: the word the deployer appends to the initcode, which CONSTRUCTOR keeps behind the runtime code
#define macro NEXT_PART() = {
${next.lines.join("\n")}
}

/// @notice Deploys the runtime code together with the word appended to the initcode
#define macro CONSTRUCTOR() = {
${ctor.lines.join("\n")}
}
`;
  const ability = last
    ? `returns the ${t} words of the permutation output`
    : `returns what part ${part + 1} returns`;
  return `${HEADER}
${includes(fork, utilsPath)}
/// @notice Poseidon2 permutation for BN254 with t = ${t}, Rf = ${roundsF}, Rp = ${roundsP}: part ${part} of ${count}, ${steps}
/// @dev takes [${inputs}, PRIME] with clean inputs, leaves the state in memory at [0, ${hexOff(32 * t)}) (${last ? "clean outputs" : "lazy values, the next entry reduces them"}; stack: garbage)
/// @dev Every ADD / MUL below was checked by the generator's bound tracker to fit in uint256
${forkNote(fork)}${stats(result.emitter, result)}
/// @dev schedule options: ${describeOptions(opts)}
#define macro POSEIDON2_PART() = {
${result.lines.join("\n")}
}

/// @notice Part ${part} entry: calldata = ${t} words (reduced mod PRIME), ${ability}
#define macro MAIN() = {
${code.lines.join("\n")}
}
${chain}`;
}

export type Vector = { input: bigint[]; output: bigint[] };

export function renderForgeTest(
  params: Params,
  vectors: Vector[],
  fork: Fork = FORKS.shanghai,
  parts = 1,
): string {
  const { t } = params;
  const name = `Poseidon2T${t}`;
  const config = fork.push0
    ? "HuffDeployer.config()"
    : `HuffDeployer.config().with_evm_version("${fork.name}")`;
  let note = "";
  if (fork.name === DEFAULT_HARDFORK) {
    note = "";
  } else if (fork.reach > 16) {
    note = `/// @dev The permutation uses EIP-8024 DUPN / SWAPN: run with FOUNDRY_PROFILE=${fork.name}\n`;
  } else {
    note = `/// @dev The permutation targets ${fork.name}: run with FOUNDRY_PROFILE=${fork.name}\n`;
  }
  let imports = "";
  let setUp: string;
  if (parts === 1) {
    const path = huffName(fork, t, "Poseidon2");
    setUp = fork.push0
      ? `        perm = HuffDeployer.deploy("${path}");`
      : `        perm = ${config}.deploy("${path}");`;
  } else {
    note += `/// @dev The permutation is split into ${parts} contracts, deployed last to first by DeployParts\n`;
    imports = `import {DeployParts} from "../${fork.name === DEFAULT_HARDFORK ? "" : "../"}${huffDir(fork)}/t${t}/DeployParts.sol";\n`;
    const codes = Array.from(
      { length: parts },
      (_, i) =>
        `        initcodes[${i}] = ${config}.creation_code("${huffName(fork, t, `Part${i}`)}");`,
    );
    setUp = `        bytes[] memory initcodes = new bytes[](${parts});
${codes.join("\n")}
        perm = DeployParts.deploy(initcodes);`;
  }
  const cases = vectors
    .map(
      (v, i) => `
    function test_vector_${i}() public view {
        uint256[${t}] memory input = [
            ${v.input.map((x) => `uint256(${hex(x)})`).join(",\n            ")}
        ];
        uint256[${t}] memory expected = [
            ${v.output.map((x) => `uint256(${hex(x)})`).join(",\n            ")}
        ];
        assertEq(_permute(input), expected, "vector ${i}");
    }`,
    )
    .join("\n");
  return `// SPDX-License-Identifier: MIT
// This file is generated by generator/huff/generate.ts. Do not edit manually.
pragma solidity ^0.8.13;

import {Test} from "forge-std/Test.sol";
import {HuffDeployer} from "foundry-huff/HuffDeployer.sol";
${imports}
/// @notice Vectors come from the BigInt reference permutation in generator/reference.ts
${note}contract ${name}Test is Test {
    uint256 constant PRIME = ${hex(PRIME)};

    address private perm;

    function setUp() public {
${setUp}
    }

    function _permute(uint256[${t}] memory input) internal view returns (uint256[${t}] memory out) {
        (bool ok, bytes memory ret) = perm.staticcall(abi.encode(input));
        require(ok, "permutation call failed");
        out = abi.decode(ret, (uint256[${t}]));
    }

    function assertEq(uint256[${t}] memory a, uint256[${t}] memory b, string memory err) internal pure {
        for (uint256 i = 0; i < ${t}; i++) {
            assertEq(a[i], b[i], err);
        }
    }
${cases}

    /// @dev inputs at or above PRIME are reduced by the entry contract
    function test_input_sanitization() public view {
        uint256[${t}] memory a;
        uint256[${t}] memory b;
        for (uint256 i = 0; i < ${t}; i++) {
            a[i] = i + 5;
            b[i] = PRIME + i + 5;
        }
        assertEq(_permute(a), _permute(b), "sanitization");
        for (uint256 i = 0; i < ${t}; i++) {
            a[i] = type(uint256).max % PRIME;
            b[i] = type(uint256).max;
        }
        assertEq(_permute(a), _permute(b), "sanitization max");
    }
}
`;
}
