// Writers for the generated Huff files and the Foundry test of a t != 4
// permutation.

import { hex, PRIME } from "../field.ts";
import type { Params } from "../params.ts";
import { MAX_REACH, dupText, type Target } from "./emitter.ts";
import {
  describeOptions,
  type BuildOptions,
  type BuildResult,
} from "./schedule.ts";

const HEADER = `// This file is generated by generator/huff/generate.ts. Do not edit manually.
// Security: https://github.com/zemse/poseidon2-evm/blob/main/SECURITY.md
`;

export function renderPermutation(
  params: Params,
  result: BuildResult,
  opts: BuildOptions,
  utilsPath: string,
  target: Target = "legacy",
): string {
  const { t, roundsF, roundsP } = params;
  const outputs = Array.from({ length: t }, (_, i) => `s${i}'`).join(", ");
  const inputs = Array.from({ length: t }, (_, i) => `s${i}`).join(", ");
  const layout =
    t <= 4
      ? `[${outputs}, PRIME, ...garbage...]`
      : `[${outputs}, ...garbage...]`;
  const includes =
    target === "amsterdam"
      ? `#include "${utilsPath}"\n#include "../Eip8024.huff"\n`
      : `#include "${utilsPath}"\n`;
  const fork =
    target === "amsterdam"
      ? `/// @dev Uses EIP-8024 DUPN / SWAPN (Eip8024.huff): runs on Amsterdam and later only\n`
      : "";
  return `${HEADER}
${includes}
/// @notice Poseidon2 permutation for BN254 with t = ${t}, Rf = ${roundsF}, Rp = ${roundsP}
/// @dev takes [${inputs}, PRIME] with clean inputs, returns ${layout} with clean outputs
/// @dev Every ADD / MUL below was checked by the generator's bound tracker to fit in uint256
${fork}/// @dev ${result.gas} gas, max stack depth ${result.maxDepth}, max dup ${result.maxDup}, ${result.bytes} bytes
/// @dev schedule options: ${describeOptions(opts)}
#define macro POSEIDON2_PERMUTATION() = {
${result.lines.join("\n")}
}
`;
}

// DUP17() .. DUP235() and SWAP17() .. SWAP235() as the raw EIP-8024 bytes,
// since neither huffc nor huff-neo knows the mnemonics. The immediate x
// encodes n = (x + 145) % 256.
export function renderEip8024(): string {
  const macros: string[] = [];
  for (const [name, opcode] of [
    ["DUP", 0xe6],
    ["SWAP", 0xe7],
  ] as const) {
    for (let n = 17; n <= MAX_REACH.amsterdam; n++) {
      const imm = (n - 145) & 0xff;
      const bytes = `0x${opcode.toString(16)}${imm.toString(16).padStart(2, "0")}`;
      macros.push(
        `#define macro ${name}${n}() = { __VERBATIM(${bytes}) }`.padEnd(52) +
          `// ${name.toLowerCase()}n ${n}`,
      );
    }
  }
  return `${HEADER}
/// @notice EIP-8024 DUPN / SWAPN (Amsterdam) for stack slots 17 to 235
/// @dev DUPn() copies the n-th item, SWAPn() swaps the top with the (n + 1)-th item, 3 gas and 2 bytes each
${macros.join("\n")}
`;
}

// Runtime bytes of the entry contract rendered by renderEntry.
export function entryBytes(t: number): number {
  const push = (c: number) => (c === 0 ? 1 : c < 256 ? 2 : 3);
  let bytes = 33; // SETUP: PUSH32 PRIME
  for (let i = 0; i < t; i++) {
    bytes += (t - i <= 16 ? 1 : 2) + push(32 * i) + 2; // dup off calldataload mod
    bytes += push(32 * i) + 1; // off mstore
  }
  return bytes + push(32 * t) + 2; // size 0x0 return
}

// Minimal entry contract for t != 4: calldata holds t words which are reduced
// mod PRIME, the permuted state is returned as t words.
export function renderEntry(params: Params): string {
  const { t } = params;
  const loads: string[] = [];
  for (let i = t - 1; i >= 0; i--) {
    const off = i === 0 ? "0x0" : "0x" + (32 * i).toString(16);
    // PRIME sits under the words loaded so far
    const stack = Array.from({ length: t - i }, (_, k) => `s${i + k}`);
    loads.push(
      `    ${dupText(t - i)} ${off} calldataload mod`.padEnd(40) +
        ` // [${stack.join(", ")}, PRIME]`,
    );
  }
  const stores: string[] = [];
  for (let i = 0; i < t; i++) {
    const off = i === 0 ? "0x0" : "0x" + (32 * i).toString(16);
    stores.push(`    ${off} mstore`);
  }
  const size = "0x" + (32 * t).toString(16);
  return `${HEADER}
#include "./Permutation.huff"

/// @notice Poseidon2 permutation entry for t = ${t}: calldata = ${t} words (reduced mod PRIME), returns ${t} words
#define macro MAIN() = {
    SETUP()                              // [PRIME]
${loads.join("\n")}

    POSEIDON2_PERMUTATION()              // [s0', ..., s${t - 1}', ...]

${stores.join("\n")}
    ${size} 0x0 return
}
`;
}

export type Vector = { input: bigint[]; output: bigint[] };

export function renderForgeTest(
  params: Params,
  vectors: Vector[],
  target: Target = "legacy",
): string {
  const { t } = params;
  const name = `Poseidon2T${t}`;
  const huffPath =
    target === "amsterdam"
      ? `bn254/huff/amsterdam/t${t}/Poseidon2`
      : `bn254/huff/t${t}/Poseidon2`;
  const fork =
    target === "amsterdam"
      ? `/// @dev The permutation uses EIP-8024 DUPN / SWAPN: run with FOUNDRY_PROFILE=amsterdam\n`
      : "";
  const cases = vectors
    .map(
      (v, i) => `
    function test_vector_${i}() public view {
        uint256[${t}] memory input = [
            ${v.input.map((x) => `uint256(${hex(x)})`).join(",\n            ")}
        ];
        uint256[${t}] memory expected = [
            ${v.output.map((x) => `uint256(${hex(x)})`).join(",\n            ")}
        ];
        assertEq(_permute(input), expected, "vector ${i}");
    }`,
    )
    .join("\n");
  return `// SPDX-License-Identifier: MIT
// This file is generated by generator/huff/generate.ts. Do not edit manually.
pragma solidity ^0.8.13;

import {Test} from "forge-std/Test.sol";
import {HuffDeployer} from "foundry-huff/HuffDeployer.sol";

/// @notice Vectors come from the BigInt reference permutation in generator/reference.ts
${fork}contract ${name}Test is Test {
    uint256 constant PRIME = ${hex(PRIME)};

    address private perm;

    function setUp() public {
        perm = HuffDeployer.deploy("${huffPath}");
    }

    function _permute(uint256[${t}] memory input) internal view returns (uint256[${t}] memory out) {
        (bool ok, bytes memory ret) = perm.staticcall(abi.encode(input));
        require(ok, "permutation call failed");
        out = abi.decode(ret, (uint256[${t}]));
    }

    function assertEq(uint256[${t}] memory a, uint256[${t}] memory b, string memory err) internal pure {
        for (uint256 i = 0; i < ${t}; i++) {
            assertEq(a[i], b[i], err);
        }
    }
${cases}

    /// @dev inputs at or above PRIME are reduced by the entry contract
    function test_input_sanitization() public view {
        uint256[${t}] memory a;
        uint256[${t}] memory b;
        for (uint256 i = 0; i < ${t}; i++) {
            a[i] = i + 5;
            b[i] = PRIME + i + 5;
        }
        assertEq(_permute(a), _permute(b), "sanitization");
        for (uint256 i = 0; i < ${t}; i++) {
            a[i] = type(uint256).max % PRIME;
            b[i] = type(uint256).max;
        }
        assertEq(_permute(a), _permute(b), "sanitization max");
    }
}
`;
}
