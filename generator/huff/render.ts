// src/bn254/huff for the default fork, src/bn254/huff/<fork> otherwise
export function huffDir(fork: Fork): string {
  return fork.name === DEFAULT_HARDFORK
    ? "src/bn254/huff"
    : `src/bn254/huff/${fork.name}`;
}

export function testDir(fork: Fork): string {
  return fork.name === DEFAULT_HARDFORK ? "test" : `test/${fork.name}`;
}

// the foundry-huff name of a contract in the width directory
export function huffName(fork: Fork, t: number, file: string): string {
  const dir = huffDir(fork).slice("src/".length);
  return `${dir}/t${t}/${file}`;
}

// includes of a permutation in the width directory
function includes(fork: Fork, utilsPath: string): string {
  let text = `#include "${utilsPath}"\n`;
  if (fork.reach > 16) text += `#include "../Eip8024.huff"\n`;
  if (!fork.push0) text += `#include "../Zero.huff"\n`;
  return text;
}

function forkNote(fork: Fork): string {
  if (fork.reach > 16) {
    return `/// @dev Uses EIP-8024 DUPN / SWAPN (Eip8024.huff): runs on Amsterdam and later only\n`;
  }
  if (!fork.push0) {
    return `/// @dev No PUSH0 (Zero.huff): runs before Shanghai as well\n`;
  }
  return "";
}

// ---- straight-line code outside the macro ----------------------------------

// Lines with their gas and bytes, for the entry and the hand-off.
class Code {
  lines: string[] = [];
  gas = 0;
  bytes = 0;
  private pending: string[] = [];
  readonly fork: Fork;

  constructor(fork: Fork) {
    this.fork = fork;
  }

  op(text: string, gas: number, bytes: number) {
    this.pending.push(text);
    this.gas += gas;
    this.bytes += bytes;
  }

  push(c: number) {
    const v = BigInt(c);
    this.op(
      pushText(v, this.fork),
      pushGas(v, this.fork),
      pushBytes(v, this.fork),
    );
  }

  dup(n: number) {
    this.op(dupText(n), GAS.dup, n <= 16 ? 1 : 2);
  }

  end(comment = "") {
    const ops = `    ${this.pending.join(" ")}`;
    this.pending = [];
    this.lines.push(comment ? `${ops.padEnd(40)} // ${comment}` : ops);
  }

  blank() {
    this.lines.push("");
  }

  text(line: string) {
    this.lines.push(line);
  }
}

// t calldata words from `base` reduced mod PRIME onto the stack, shadowed
// inputs also stored to their slot; without `reduce` (a part after the
// first, whose words are the lazy values the part before leaves) the words
// as they are, any shadowed one loaded from calldata by the schedule
function loads(
  code: Code,
  t: number,
  inputSlots: (number | undefined)[],
  base = 0,
  reduce = true,
) {
  code.op("SETUP()", GAS.push, 33);
  code.end("[PRIME]");
  for (let i = t - 1; i >= 0; i--) {
    if (reduce) {
      // PRIME sits under the words loaded so far, pushed again once out of
      // reach (same gas, 33 bytes)
      if (t - i <= code.fork.reach) code.dup(t - i);
      else code.op("[PRIME]", GAS.push, 33);
    }
    code.push(base + 32 * i);
    code.op("calldataload", 3, 1);
    if (reduce) code.op("mod", GAS.mod, 1);
    const slot = inputSlots[i];
    if (slot !== undefined) {
      code.dup(1);
      code.push(slot);
      code.op("mstore", GAS.mstore, 1);
    }
    const stack = Array.from({ length: t - i }, (_, k) => `s${i + k}`);
    code.end(`[${stack.join(", ")}, PRIME]`);
  }
}

// 32 n, from MSIZE (2 gas, 1 byte) where the words before it are all the frame
// has touched: the code before wrote `memory` bytes and the return stores
// [0, 32 n), else PUSH
function size(code: Code, n: number, memory: number) {
  if (Math.ceil(memory / 32) <= n) code.op("msize", 2, 1);
  else code.push(32 * n);
}

// return t words: from the stack top (in state order) or from memory [0, 32t),
// after code that wrote `memory` bytes (Infinity when not known yet)
function ret(code: Code, t: number, fromMemory: boolean, memory: number) {
  if (!fromMemory) {
    for (let i = 0; i < t; i++) {
      size(code, i, memory);
      code.op("mstore", GAS.mstore, 1);
      code.end();
    }
  }
  size(code, t, memory);
  code.push(0);
  code.op("return", 0, 1);
  code.end();
}

// STATICCALL the next part with the state at [0, 32t) and return its
// output: the call's arguments and the address (NEXT_PART, a PUSH32), then
// HAND_OVER with the call itself
function handOver(code: Code, t: number, part: number, memory: number) {
  code.text(
    `    // forward the state to part ${part + 1} and return its output`,
  );
  size(code, t, memory);
  code.push(0);
  size(code, t, memory);
  code.push(0);
  code.op("NEXT_PART()", GAS.push, NEXT_PART_BYTES);
  const tail = handOverTail(code.fork, t, memory);
  code.op("HAND_OVER()", tail.gas, tail.bytes);
  code.end("[output]");
}

// the PUSH32 of the next part's address, patched by the constructor
const NEXT_PART_BYTES = 33;

// the call to the address on top, the check of its return data and the
// return of it (HAND_OVER)
function handOverTail(fork: Fork, t: number, memory: number): Code {
  const code = new Code(fork);
  code.op("gas", 2, 1);
  code.op("staticcall", fork.coldAccount, 1);
  code.end("[success]");
  code.op("returndatasize", 2, 1);
  size(code, t, memory);
  code.op("eq", 3, 1);
  code.op("and", 3, 1);
  code.op("ok", 3, 3);
  code.op("jumpi", 10, 1);
  code.end();
  // the revert branch: bytes only, a call that succeeds skips it
  code.op(pushText(0n, fork), 0, pushBytes(0n, fork));
  code.op(pushText(0n, fork), 0, pushBytes(0n, fork));
  code.op("revert", 0, 1);
  code.end();
  code.op("ok:", 1, 1);
  code.end();
  ret(code, t, true, memory);
  return code;
}

// Gas and bytes of a part's code around the permutation macro: the entry
// (calldata loads, reduced unless `lazy`) and the tail (return or hand-over,
// the hand-over with the cold STATICCALL but without the callee), around code
// that writes `memory` (Infinity for a budget).
export type Overhead = { entryGas: number; tailGas: number; bytes: number };

export function overhead(
  fork: Fork,
  t: number,
  inputSlots: (number | undefined)[],
  stateInMemory: boolean,
  handsOver: boolean,
  lazy = false,
  memory = Infinity,
): Overhead {
  const entry = new Code(fork);
  loads(entry, t, inputSlots, 0, !lazy);
  const tail = new Code(fork);
  if (handsOver) handOver(tail, t, 0, memory);
  else ret(tail, t, stateInMemory, memory);
  return {
    entryGas: entry.gas,
    tailGas: tail.gas,
    bytes: entry.bytes + tail.bytes,
  };
}

export { memoryGas };

// Runtime bytes of the entry contract around a permutation (loads, return).
export function entryBytes(
  fork: Fork,
  t: number,
  inputSlots: (number | undefined)[] = [],
  stateInMemory = false,
  memory = Infinity,
): number {
  return overhead(fork, t, inputSlots, stateInMemory, false, false, memory)
    .bytes;
}

// ---- files -----------------------------------------------------------------

export function renderPermutation(
  params: Params,
  result: BuildResult,
  opts: BuildOptions,
  utilsPath: string,
  fork: Fork = FORKS.shanghai,
): string {
  const { t, roundsF, roundsP } = params;
  const outputs = Array.from({ length: t }, (_, i) => `s${i}'`).join(", ");
  const inputs = Array.from({ length: t }, (_, i) => `s${i}`).join(", ");
  const layout = result.stateInMemory
    ? `the state in memory at [0, ${hexOff(32 * t)}) with clean outputs (stack: garbage)`
    : t <= 4
      ? `[${outputs}, PRIME, ...garbage...] with clean outputs`
      : `[${outputs}, ...garbage...] with clean outputs`;
  return `${HEADER}
${includes(fork, utilsPath)}
/// @notice Poseidon2 permutation for BN254 with t = ${t}, Rf = ${roundsF}, Rp = ${roundsP}
/// @dev takes [${inputs}, PRIME] with clean inputs, returns ${layout}
/// @dev Every ADD / MUL below was checked by the generator's bound tracker to fit in uint256
${forkNote(fork)}${stats(result.emitter, result)}
/// @dev schedule options: ${describeOptions(opts)}
#define macro POSEIDON2_PERMUTATION() = {
${result.lines.join("\n")}
}
${tables(result)}`;
}

// the round constants of the shared body's calls as code tables, which
// huffc appends to the runtime code behind the macro
function tables(result: BuildResult): string {
  return result.tables
    .map(
      ({ name, words }, i) => `
/// @notice Round constants of call ${i} of the shared body, CODECOPYed to memory at the call
#define table ${name} {
${words.map((w) => `    ${hex(w)}`).join("\n")}
}
`,
    )
    .join("");
}

function stats(e: Emitter, result: BuildResult): string {
  let text = `/// @dev ${result.gas} gas, max stack depth ${result.maxDepth}, max dup ${result.maxDup}, ${result.bytes} bytes`;
  if (e.stores > 0 || e.loads > 0) {
    text += `, ${e.stores} values shadowed in memory, ${e.loads} loads`;
  }
  return text;
}

function hexOff(n: number): string {
  return "0x" + n.toString(16);
}

// DUP17() .. DUP235() and SWAP17() .. SWAP235() as the raw EIP-8024 bytes,
// since neither huffc nor huff-neo knows the mnemonics. The immediate x
// encodes n = (x + 145) % 256.
export function renderEip8024(reach: number): string {
  const macros: string[] = [];
  for (const [name, opcode] of [
    ["DUP", 0xe6],
    ["SWAP", 0xe7],
  ] as const) {
    for (let n = 17; n <= reach; n++) {
      const imm = (n - 145) & 0xff;
      const bytes = `0x${opcode.toString(16)}${imm.toString(16).padStart(2, "0")}`;
      macros.push(
        `#define macro ${name}${n}() = { __VERBATIM(${bytes}) }`.padEnd(52) +
          `// ${name.toLowerCase()}n ${n}`,
      );
    }
  }
  return `${HEADER}
/// @notice EIP-8024 DUPN / SWAPN (Amsterdam) for stack slots 17 to ${reach}
/// @dev DUPn() copies the n-th item, SWAPn() swaps the top with the (n + 1)-th item, 3 gas and 2 bytes each
${macros.join("\n")}
`;
}

// PUSH1 0x00 for the forks before Shanghai: huffc turns every zero literal
// into PUSH0 (EIP-3855), which they do not have.
// next to the Part<i>.huff files of a split width
export function renderDeployParts(): string {
  return `// SPDX-License-Identifier: MIT
${HEADER}pragma solidity ^0.8.13;

/// @notice Deploys the parts of a split Huff permutation (generator/huff/split.ts)
/// @dev Parts go up last to first: each initcode but the last gets the address
/// of the part after it appended as a 32-byte word, which that part's
/// constructor keeps behind its runtime code. The address returned is part 0,
/// the contract that takes the t input words and returns the t output words.
library DeployParts {
    function deploy(bytes[] memory initcodes) internal returns (address first) {
        address next;
        for (uint256 i = initcodes.length; i > 0; i--) {
            bytes memory code =
                i == initcodes.length ? initcodes[i - 1] : bytes.concat(initcodes[i - 1], abi.encode(next));
            assembly {
                next := create(0, add(code, 0x20), mload(code))
            }
            require(next != address(0), "part deployment failed");
        }
        return next;
    }
}
`;
}

export function renderZero(): string {
  return `${HEADER}
/// @notice A zero as PUSH1 0x00 (3 gas, 2 bytes) for the forks without EIP-3855 PUSH0, which huffc emits for any zero literal
#define macro ZERO() = { __VERBATIM(0x6000) }
`;
}

// Minimal entry contract for t != 4: calldata holds t words which are reduced
// mod PRIME, the permuted state is returned as t words.
export function renderEntry(
  params: Params,
  fork: Fork = FORKS.shanghai,
  result?: BuildResult,
): string {
  const { t } = params;
  const code = new Code(fork);
  loads(code, t, result?.inputSlots ?? []);
  code.blank();
  const inMemory = result?.stateInMemory ?? false;
  code.op("POSEIDON2_PERMUTATION()", 0, 0);
  code.end(
    inMemory
      ? `state at memory [0, ${hexOff(32 * t)})`
      : `[s0', ..., s${t - 1}', ...]`,
  );
  code.blank();
  ret(code, t, inMemory, result?.memory ?? Infinity);
  return `${HEADER}
#include "./Permutation.huff"

/// @notice Poseidon2 permutation entry for t = ${t}: calldata = ${t} words (reduced mod PRIME), returns ${t} words
#define macro MAIN() = {
${code.lines.join("\n")}
}
`;
}

// ---- the t = 4 hash entry --------------------------------------------------

// The code of MAIN around POSEIDON2_HASH_ROUNDS and what each arity's call
// costs. The arity comes from calldatasize (a selector and 1, 2 or 3
// words): hash_2 falls through the first test, hash_3 the second, hash_1
// branches twice, and the two that do not fall through to the rounds jump
// to them. Each arity runs its own round 0 (its prologue, schedule.ts
// hashRound0), which loads its words; the rounds leave s0' on top.
export type HashEntry = {
  lines: string[];
  // call gas of hash_1, hash_2, hash_3 (memory expansion included)
  gas: number[];
  // runtime bytes
  bytes: number;
};

// `rounds` is the gas, bytes and memory of the rounds macro, 0, 0 and Infinity
// before it is built (the overhead decides its code size budget).
export function hashEntry(
  fork: Fork,
  prologues: Prologue[],
  rounds: { gas: number; bytes: number; memory: number } = {
    gas: 0,
    bytes: 0,
    memory: Infinity,
  },
): HashEntry {
  const by = (n: number) => {
    const p = prologues.find((p) => p.n === n);
    if (!p) throw new Error(`no prologue for hash_${n}`);
    return p;
  };
  // calldatasize <op> 0x44 decides the branch
  const test = (code: Code, op: string, label: string) => {
    code.op("calldatasize", 2, 1);
    code.push(0x44);
    code.op(op, 3, 1);
    code.op(label, 3, 3);
    code.op("jumpi", 10, 1);
    code.end();
  };
  const label = (code: Code, name: string) => {
    code.op(`${name}:`, 1, 1);
    code.end();
  };
  const branch = (code: Code, p: Prologue) => {
    code.op("SETUP()", GAS.push, 33);
    code.end("[PRIME]");
    for (const line of p.lines) code.text(line);
    code.gas += p.gas;
    code.bytes += p.bytes;
  };
  const jump = (code: Code) => {
    code.op("rounds", 3, 3);
    code.op("jump", 8, 1);
    code.end();
  };

  const dispatch = new Code(fork);
  dispatch.text(
    "    // hash_2 (a selector and two words) falls through, the other arities branch on calldatasize",
  );
  test(dispatch, "sub", "not_hash_2");
  const b2 = new Code(fork);
  branch(b2, by(2));
  const tail = new Code(fork);
  label(tail, "rounds");
  tail.op("POSEIDON2_HASH_ROUNDS()", rounds.gas, rounds.bytes);
  tail.end("[s0', ...]");
  ret(tail, 1, false, rounds.memory);
  const gate = new Code(fork);
  gate.blank();
  label(gate, "not_hash_2");
  test(gate, "gt", "hash_1");
  const b3 = new Code(fork);
  branch(b3, by(3));
  jump(b3);
  const b1 = new Code(fork);
  b1.blank();
  label(b1, "hash_1");
  branch(b1, by(1));
  jump(b1);

  const memory = memoryGas(32);
  const shared = dispatch.gas + tail.gas + memory;
  const parts = [dispatch, b2, tail, gate, b3, b1];
  return {
    lines: parts.flatMap((c) => c.lines),
    gas: [
      shared + gate.gas + b1.gas,
      shared + b2.gas,
      shared + gate.gas + b3.gas,
    ],
    bytes: parts.reduce((sum, c) => sum + c.bytes, 0),
  };
}

// t4/Poseidon2.huff: the rounds after round 0 as POSEIDON2_HASH_ROUNDS and
// the hash_1 / hash_2 / hash_3 entry around them.
export function renderHashEntry(
  params: Params,
  fork: Fork,
  rounds: Best,
  prologues: Prologue[],
  utilsPath: string,
): string {
  const { t, roundsF, roundsP } = params;
  const { result, opts } = rounds;
  const total = roundsF + roundsP;
  const entry = hashEntry(fork, prologues, result);
  // round 0 leaves a PRIME copy under s0' and another under its dead values
  const inputs = [
    "s0",
    "PRIME",
    ...Array.from({ length: t - 1 }, (_, i) => `s${i + 1}`),
  ]
    .concat(new Array(HASH_DEAD).fill("dead"), "PRIME")
    .join(", ");
  // the rounds run on top of a prologue's garbage
  const depth =
    Math.max(...prologues.map((p) => p.depth - t - 2 - HASH_DEAD)) +
    result.maxDepth;
  const gas = entry.gas.map((g, i) => `hash_${i + 1} ${g} gas`).join(", ");
  return `${HEADER}
${includes(fork, utilsPath)}
/// @notice Poseidon2 rounds 1 to ${total - 1} for BN254 with t = ${t}, Rf = ${roundsF}, Rp = ${roundsP}: the hash entry's rounds after round 0, the last one as far as s0' needs
/// @dev takes [${inputs}] with the lazy values round 0 leaves (hashRound0 of any arity), returns [s0', ...garbage...] with s0' clean
/// @dev Every ADD / MUL below was checked by the generator's bound tracker to fit in uint256
${forkNote(fork)}${stats(result.emitter, result)}
/// @dev schedule options: ${describeOptions(opts)}
#define macro POSEIDON2_HASH_ROUNDS() = {
${result.lines.join("\n")}
}

/// @notice hash_1 / hash_2 / hash_3 of IPoseidon2 (the arity from calldatasize, the selector is not checked): the sponge state [x0, x1, x2, n << 64] permuted once, s0' returned
/// @dev Each arity runs its own round 0, with the missing words and the capacity n << 64 folded into its constants, then the rounds above
/// @dev ${gas}, ${entry.bytes} runtime bytes, max stack depth ${depth}
#define macro MAIN() = {
${entry.lines.join("\n")}
}
`;
}

// Part `part` of `count` of a split permutation: the rounds of its range,
// the entry, and the hand-over to the next part or the return.
export function renderPart(
  params: Params,
  result: BuildResult,
  opts: BuildOptions,
  utilsPath: string,
  fork: Fork,
  part: number,
  count: number,
): string {
  const { t, roundsF, roundsP } = params;
  const { from, to } = result.range;
  const inputs = Array.from({ length: t }, (_, i) => `s${i}`).join(", ");
  const last = part === count - 1;
  const steps =
    from === 0
      ? `the initial linear layer and rounds 0 to ${to - 2}`
      : `rounds ${from - 1} to ${to - 2}`;
  // a part after the first takes the lazy values the part before leaves
  const takes =
    from === 0
      ? "with clean inputs"
      : `with inputs below ${HANDOVER_BOUND_TEXT} (what part ${part - 1} leaves)`;
  const words =
    from === 0
      ? "reduced mod PRIME"
      : `as part ${part - 1} leaves them, below ${HANDOVER_BOUND_TEXT}`;
  const code = new Code(fork);
  loads(code, t, result.inputSlots, 0, from === 0);
  code.blank();
  code.op("POSEIDON2_PART()", 0, 0);
  code.end(`state at memory [0, ${hexOff(32 * t)})`);
  code.blank();
  if (last) ret(code, t, true, result.memory);
  else handOver(code, t, part, result.memory);
  // a 32-byte literal with its top byte set is a PUSH32 (a zero would be
  // PUSH0, and huffc drops the zeros of a __VERBATIM)
  const next = new Code(fork);
  next.op(`0x${"ff".repeat(32)}`, 0, 0);
  next.end("[next]");
  const tail = handOverTail(fork, t, result.memory);
  const ctor = new Code(fork);
  ctor.op("__codesize(CONSTRUCTOR)", 0, 0);
  ctor.end("[c]");
  ctor.op("dup1 codesize sub", 0, 0);
  ctor.end("[len, c]");
  ctor.op("dup1 swap2", 0, 0);
  ctor.push(0);
  ctor.op("codecopy", 0, 0);
  ctor.end("[len]");
  ctor.op("0x20 swap1 sub", 0, 0);
  ctor.end("[size]");
  ctor.op("dup1 mload", 0, 0);
  ctor.end("[next, size]");
  ctor.op("__codesize(HAND_OVER) __codesize(MAIN) sub 0x20 swap1 sub", 0, 0);
  ctor.end("[offset, next, size]");
  ctor.op("mstore", 0, 0);
  ctor.end("[size]");
  ctor.push(0);
  ctor.op("return", 0, 0);
  ctor.end();
  const chain = last
    ? ""
    : `
/// @notice Address of part ${part + 1}: a PUSH32 that CONSTRUCTOR patches with the word the deployer appends to the initcode
#define macro NEXT_PART() = {
${next.lines.join("\n")}
}

/// @notice STATICCALLs the address on top with the state at [0, ${hexOff(32 * t)}) and returns its output
#define macro HAND_OVER() = {
${tail.lines.join("\n")}
}

/// @notice Deploys the runtime code with the word appended to the initcode patched into NEXT_PART, whose immediate ends where HAND_OVER begins
#define macro CONSTRUCTOR() = {
${ctor.lines.join("\n")}
}
`;
  const ability = last
    ? `returns the ${t} words of the permutation output`
    : `returns what part ${part + 1} returns`;
  return `${HEADER}
${includes(fork, utilsPath)}
/// @notice Poseidon2 permutation for BN254 with t = ${t}, Rf = ${roundsF}, Rp = ${roundsP}: part ${part} of ${count}, ${steps}
/// @dev takes [${inputs}, PRIME] ${takes}, leaves the state in memory at [0, ${hexOff(32 * t)}) (${last ? "clean outputs" : `lazy values below ${HANDOVER_BOUND_TEXT}, which the next part takes as they are`}; stack: garbage)
/// @dev Every ADD / MUL below was checked by the generator's bound tracker to fit in uint256
${forkNote(fork)}${stats(result.emitter, result)}
/// @dev schedule options: ${describeOptions(opts)}
#define macro POSEIDON2_PART() = {
${result.lines.join("\n")}
}
${tables(result)}
/// @notice Part ${part} entry: calldata = ${t} words (${words}), ${ability}
#define macro MAIN() = {
${code.lines.join("\n")}
}
${chain}`;
}

// Foundry test of the t = 4 hash entry on a fork other than the default
// (the default's is the hand-written test/Poseidon2.t.sol): hash_1 / hash_2
// / hash_3 of the shared inputs against the reference sponge, and the
// reduction of inputs at or above PRIME.
export function renderHashTest(
  params: Params,
  inputs: bigint[][],
  fork: Fork,
): string {
  const config = fork.push0
    ? "HuffDeployer"
    : `HuffDeployer.config().with_evm_version("${fork.name}")`;
  const path = huffName(fork, params.t, "Poseidon2");
  const cases = [1, 2, 3]
    .map((n) => {
      const rows = inputs.map((input) => {
        const args = input.slice(0, n);
        const words = [...args, hashSponge(params, args)].map(
          (x) => `uint256(${hex(x)})`,
        );
        return `[${words.join(", ")}]`;
      });
      const args = Array.from({ length: n }, (_, i) => `v[${i}]`).join(", ");
      return `
    function test_hash_${n}_vectors() public view {
        uint256[${n + 1}][${inputs.length}] memory vectors = [
            ${rows.join(",\n            ")}
        ];
        for (uint256 i = 0; i < vectors.length; i++) {
            uint256[${n + 1}] memory v = vectors[i];
            assertEq(hash.hash_${n}(${args}), v[${n}], "hash_${n} vector");
        }
    }`;
    })
    .join("\n");
  return `// SPDX-License-Identifier: MIT
// This file is generated by generator/huff/generate.ts. Do not edit manually.
pragma solidity ^0.8.13;

import {Test} from "forge-std/Test.sol";
import {HuffDeployer} from "foundry-huff/HuffDeployer.sol";
import {IPoseidon2} from "../../src/IPoseidon2.sol";

/// @notice Vectors come from the BigInt reference sponge in generator/shared/reference.ts
/// @dev The hash entry targets ${fork.name}: run with FOUNDRY_PROFILE=${fork.name}
contract Poseidon2T${params.t}Test is Test {
    uint256 constant PRIME = ${hex(PRIME)};

    IPoseidon2 private hash;

    function setUp() public {
        hash = IPoseidon2(${config}.deploy("${path}"));
    }
${cases}

    /// @dev inputs at or above PRIME are reduced by the entry
    function test_input_sanitization() public view {
        uint256 max = type(uint256).max;
        assertEq(hash.hash_1(PRIME + 5), hash.hash_1(5), "hash_1");
        assertEq(hash.hash_2(PRIME + 5, max), hash.hash_2(5, max % PRIME), "hash_2");
        assertEq(hash.hash_3(PRIME + 5, max, PRIME), hash.hash_3(5, max % PRIME, 0), "hash_3");
    }
}
`;
}

export type Vector = { input: bigint[]; output: bigint[] };

export function renderForgeTest(
  params: Params,
  vectors: Vector[],
  fork: Fork = FORKS.shanghai,
  parts = 1,
): string {
  const { t } = params;
  const name = `Poseidon2T${t}`;
  const config = fork.push0
    ? "HuffDeployer.config()"
    : `HuffDeployer.config().with_evm_version("${fork.name}")`;
  let note = "";
  if (fork.name === DEFAULT_HARDFORK) {
    note = "";
  } else if (fork.reach > 16) {
    note = `/// @dev The permutation uses EIP-8024 DUPN / SWAPN: run with FOUNDRY_PROFILE=${fork.name}\n`;
  } else {
    note = `/// @dev The permutation targets ${fork.name}: run with FOUNDRY_PROFILE=${fork.name}\n`;
  }
  let imports = "";
  let setUp: string;
  if (parts === 1) {
    const path = huffName(fork, t, "Poseidon2");
    setUp = fork.push0
      ? `        perm = HuffDeployer.deploy("${path}");`
      : `        perm = ${config}.deploy("${path}");`;
  } else {
    note += `/// @dev The permutation is split into ${parts} contracts, deployed last to first by DeployParts\n`;
    imports = `import {DeployParts} from "../${fork.name === DEFAULT_HARDFORK ? "" : "../"}${huffDir(fork)}/t${t}/DeployParts.sol";\n`;
    const codes = Array.from(
      { length: parts },
      (_, i) =>
        `        initcodes[${i}] = ${config}.creation_code("${huffName(fork, t, `Part${i}`)}");`,
    );
    setUp = `        bytes[] memory initcodes = new bytes[](${parts});
${codes.join("\n")}
        perm = DeployParts.deploy(initcodes);`;
  }
  const cases = vectors
    .map(
      (v, i) => `
    function test_vector_${i}() public view {
        uint256[${t}] memory input = [
            ${v.input.map((x) => `uint256(${hex(x)})`).join(",\n            ")}
        ];
        uint256[${t}] memory expected = [
            ${v.output.map((x) => `uint256(${hex(x)})`).join(",\n            ")}
        ];
        assertEq(_permute(input), expected, "vector ${i}");
    }`,
    )
    .join("\n");
  return `// SPDX-License-Identifier: MIT
// This file is generated by generator/huff/generate.ts. Do not edit manually.
pragma solidity ^0.8.13;

import {Test} from "forge-std/Test.sol";
import {HuffDeployer} from "foundry-huff/HuffDeployer.sol";
${imports}
/// @notice Vectors come from the BigInt reference permutation in generator/shared/reference.ts
${note}contract ${name}Test is Test {
    uint256 constant PRIME = ${hex(PRIME)};

    address private perm;

    function setUp() public {
${setUp}
    }

    function _permute(uint256[${t}] memory input) internal view returns (uint256[${t}] memory out) {
        (bool ok, bytes memory ret) = perm.staticcall(abi.encode(input));
        require(ok, "permutation call failed");
        out = abi.decode(ret, (uint256[${t}]));
    }

    function assertEq(uint256[${t}] memory a, uint256[${t}] memory b, string memory err) internal pure {
        for (uint256 i = 0; i < ${t}; i++) {
            assertEq(a[i], b[i], err);
        }
    }
${cases}

    /// @dev inputs at or above PRIME are reduced by the entry contract
    function test_input_sanitization() public view {
        uint256[${t}] memory a;
        uint256[${t}] memory b;
        for (uint256 i = 0; i < ${t}; i++) {
            a[i] = i + 5;
            b[i] = PRIME + i + 5;
        }
        assertEq(_permute(a), _permute(b), "sanitization");
        for (uint256 i = 0; i < ${t}; i++) {
            a[i] = type(uint256).max % PRIME;
            b[i] = type(uint256).max;
        }
        assertEq(_permute(a), _permute(b), "sanitization max");
    }
}
`;
}
