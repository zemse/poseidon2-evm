#!/bin/sh
# Writes Poseidon2/Evm/ForkData.lean from ethereum/execution-specs: for Cancun, Prague, Osaka and
# Amsterdam, the opcodes each fork defines (`instructions/__init__`) and the static gas of every
# opcode the checker accepts (`vm/gas`, `GasCosts`), with the memory expansion constants. For
# each opcode it checks the byte the fork assigns to the mnemonic and that the function the fork
# runs for it charges the constant named here (STOP and REVERT: no `OPCODE_` constant). Fails on
# any mismatch. Fetches the sources with curl into a temporary directory (as .txt), nothing else.
# Run from anywhere; `git diff formal-verification/Poseidon2/Evm/ForkData.lean` afterwards.
set -eu
cd "$(dirname "$0")/.."
# Cancun, Prague, Osaka from the default branch, Amsterdam from its fork branch (forks/amsterdam,
# whose vm/ differs from the default branch's only in blank lines).
main=a6c4bcf4d850a00ee72953f44e60ad80921095d0
ams=16898000911c1e3caa57be08509536c10ae92d3e
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
files="gas instructions/__init__ instructions/arithmetic instructions/bitwise instructions/comparison
instructions/control_flow instructions/environment instructions/memory instructions/stack
instructions/system"
for fork in cancun prague osaka amsterdam; do
  rev=$main
  [ "$fork" = amsterdam ] && rev=$ams
  mkdir -p "$tmp/$fork/instructions"
  for f in $files; do
    curl -sfL "https://raw.githubusercontent.com/ethereum/execution-specs/$rev/src/ethereum/forks/$fork/vm/$f.py" \
      -o "$tmp/$fork/$f.txt"
  done
done

# The opcodes the checker accepts: mnemonic, static gas constant, per word constant.
entries="STOP - -
ADD OPCODE_ADD -
MUL OPCODE_MUL -
SUB OPCODE_SUB -
DIV OPCODE_DIV -
MOD OPCODE_MOD -
ADDMOD OPCODE_ADDMOD -
MULMOD OPCODE_MULMOD -
LT OPCODE_LT -
GT OPCODE_GT -
SLT OPCODE_SLT -
SGT OPCODE_SGT -
EQ OPCODE_EQ -
ISZERO OPCODE_ISZERO -
AND OPCODE_AND -
OR OPCODE_OR -
XOR OPCODE_XOR -
NOT OPCODE_NOT -
SHL OPCODE_SHL -
SHR OPCODE_SHR -
CALLVALUE OPCODE_CALLVALUE -
CALLDATALOAD OPCODE_CALLDATALOAD -
CALLDATASIZE OPCODE_CALLDATASIZE -
CALLDATACOPY OPCODE_CALLDATACOPY_BASE OPCODE_COPY_PER_WORD
CODECOPY OPCODE_CODECOPY_BASE OPCODE_COPY_PER_WORD
RETURNDATASIZE OPCODE_RETURNDATASIZE -
POP OPCODE_POP -
MLOAD OPCODE_MLOAD_BASE -
MSTORE OPCODE_MSTORE_BASE -
JUMP OPCODE_JUMP -
JUMPI OPCODE_JUMPI -
MSIZE OPCODE_MSIZE -
JUMPDEST OPCODE_JUMPDEST -
PUSH0 OPCODE_PUSH0 -"
i=1
while [ $i -le 32 ]; do entries="$entries
PUSH$i OPCODE_PUSH -"; i=$((i + 1)); done
i=1
while [ $i -le 16 ]; do entries="$entries
DUP$i OPCODE_DUP -"; i=$((i + 1)); done
i=1
while [ $i -le 16 ]; do entries="$entries
SWAP$i OPCODE_SWAP -"; i=$((i + 1)); done
entries="$entries
DUPN OPCODE_DUPN -
SWAPN OPCODE_SWAPN -
RETURN ZERO -
REVERT - -"

die() { echo "forks.sh: $*" >&2; touch "$tmp/fail"; exit 1; }

# value <fork> <constant>: the constant's value in GasCosts, tiers resolved.
value() {
  rhs=$(sed -n "s/^    $2: Final\[[A-Za-z]*\] = \(.*\)$/\1/p" "$tmp/$1/gas.txt" | head -n 1)
  [ -n "$rhs" ] || die "$1: no $2"
  rhs=$(echo "$rhs" | sed 's/^ExecutionGas(\(.*\))$/\1/; s/^Uint(\([0-9]*\))$/\1/')
  case $rhs in
    *[!0-9]*) value "$1" "$rhs" ;;
    *) echo "$rhs" ;;
  esac
}

# body <file> <function>: the function's source.
body() {
  awk -v n="def $2(" 'index($0, n) == 1 { p = 1; print; next } p && /^(def |class |@)/ { p = 0 } p' "$1"
}

out=Poseidon2/Evm/ForkData.lean
{
  echo "-- Generated by \`scripts/forks.sh\` from ethereum/execution-specs. Do not edit."
  echo
  echo "/-!"
  echo "Transcribed by \`scripts/forks.sh\` from https://github.com/ethereum/execution-specs,"
  echo "\`src/ethereum/forks/<fork>/vm/\`: Cancun, Prague and Osaka at \`$main\`, Amsterdam at"
  echo "\`$ams\` (branch \`forks/amsterdam\`). Each entry is checked there against the byte the"
  echo "fork assigns to the mnemonic and the constant the function it runs charges."
  echo "-/"
  echo
  echo "namespace Poseidon2.Evm.Forks"
  echo
  echo "/-- The static gas of one opcode in a fork: its byte, mnemonic, the execution-specs constants"
  echo "charged (\`\"\"\`: none, memory expansion only), the gas and the gas per word copied. -/"
  echo "structure Cost where"
  echo "  op : Nat"
  echo "  mnemonic : String"
  echo "  constants : String"
  echo "  gas : Nat"
  echo "  perWord : Nat"
  echo "  deriving Repr, DecidableEq"
  for fork in cancun prague osaka amsterdam; do
    init="$tmp/$fork/instructions/__init__.txt"
    mask=$(sed -n 's/^    [A-Z0-9_]* = 0x\([0-9A-Fa-f]*\)$/\1/p' "$init" | tr a-f A-F | sort -u |
      awk 'BEGIN { for (i = 0; i < 16; i++) h[sprintf("%X", i)] = i }
        { v = 0; for (i = 1; i <= length($0); i++) v = v * 16 + h[substr($0, i, 1)]; print v }' |
      sort -n | tr '\n' ',' | sed 's/,$//')
    echo
    echo "/-- The opcodes $fork defines (\`Ops\` in \`instructions/__init__\`). -/"
    echo "def ${fork}Defined : List Nat := [$mask]"
    echo
    echo "/-- The static gas in $fork of the opcodes the checker accepts that $fork defines. -/"
    echo "def ${fork}Gas : List Cost := ["
    echo "$entries" | while read -r mn base word; do
      byte=$(sed -n "s/^    $mn = 0x\([0-9A-Fa-f]*\)$/\1/p" "$init")
      [ -n "$byte" ] || continue
      impl=$(sed -n "s/^    Ops\.$mn: \([a-z_]*\)_instructions\.\([a-z0-9_]*\),$/\1 \2/p" "$init")
      [ -n "$impl" ] || die "$fork: no implementation of $mn"
      mod=${impl% *}
      fn=${impl#* }
      case $fn in
        push[0-9]*) fn=push_n ;;
        dup[1-9]*) fn=dup_n ;;
        swap[1-9]*) fn=swap_n ;;
      esac
      src=$(body "$tmp/$fork/instructions/$mod.txt" "$fn")
      [ -n "$src" ] || die "$fork: no function $fn for $mn"
      if [ "$base" = - ]; then
        echo "$src" | grep -q 'GasCosts\.OPCODE_' && die "$fork: $fn charges an opcode constant"
        gas=0
        name=""
      else
        echo "$src" | grep -q "GasCosts\.$base\([^A-Z0-9_]\|$\)" || die "$fork: $fn does not charge $base"
        gas=$(value "$fork" "$base")
        name=$base
      fi
      if [ "$word" = - ]; then
        per=0
      else
        echo "$src" | grep -q "GasCosts\.$word\([^A-Z0-9_]\|$\)" || die "$fork: $fn does not charge $word"
        per=$(value "$fork" "$word")
        name="$name + $word"
      fi
      echo "  ⟨0x$byte, \"$mn\", \"$name\", ${gas}, ${per}⟩,"
    done | sed "\$ s/,\$//"
    [ ! -f "$tmp/fail" ] || exit 1
    echo "]"
    mem=$(value "$fork" MEMORY_PER_WORD)
    quad=$(body "$tmp/$fork/gas.txt" calculate_memory_gas_cost |
      sed -n 's/^ *quadratic_cost = size_in_words \*\* Uint(2) \/\/ Uint(\([0-9]*\))$/\1/p')
    [ -n "$quad" ] || die "$fork: memory cost formula changed"
    echo
    echo "/-- $fork's \`calculate_memory_gas_cost\`: \`MEMORY_PER_WORD\` and the quadratic divisor. -/"
    echo "def ${fork}Mem : Nat × Nat := ($mem, $quad)"
  done
  echo
  echo "end Poseidon2.Evm.Forks"
} > "$tmp/out"
mv "$tmp/out" "$out"
echo "wrote $out"
