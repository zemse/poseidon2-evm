/// The test_vector_<i> functions of a Foundry test (shared by the Yul one).
pub fn render_vector_cases(t: usize, vectors: &[Vector]) -> String {
    let words = |xs: &[U256]| {
        xs.iter()
            .map(|x| format!("uint256({})", hex(*x)))
            .collect::<Vec<_>>()
            .join(",\n            ")
    };
    vectors
        .iter()
        .enumerate()
        .map(|(i, v)| {
            format!(
                "
    function test_vector_{i}() public view {{
        uint256[{t}] memory input = [
            {}
        ];
        uint256[{t}] memory expected = [
            {}
        ];
        assertEq(_permute(input), expected, \"vector {i}\");
    }}",
                words(&v.input),
                words(&v.output)
            )
        })
        .collect::<Vec<_>>()
        .join("\n")
}

pub fn render_forge_test(params: &Params, vectors: &[Vector], fork: &Fork, parts: usize) -> String {
    let t = params.t;
    let name = format!("Poseidon2T{t}");
    let config = if fork.push0 {
        "HuffDeployer.config()".to_string()
    } else {
        format!("HuffDeployer.config().with_evm_version(\"{}\")", fork.name)
    };
    let mut note = if fork.name == DEFAULT_HARDFORK {
        String::new()
    } else if fork.reach > 16 {
        format!(
            "/// @dev The permutation uses EIP-8024 DUPN / SWAPN: run with FOUNDRY_PROFILE={}\n",
            fork.name
        )
    } else {
        format!(
            "/// @dev The permutation targets {}: run with FOUNDRY_PROFILE={}\n",
            fork.name, fork.name
        )
    };
    let mut imports = String::new();
    let set_up = if parts == 1 {
        let path = huff_name(fork, t, "Poseidon2");
        if fork.push0 {
            format!("        perm = HuffDeployer.deploy(\"{path}\");")
        } else {
            format!("        perm = {config}.deploy(\"{path}\");")
        }
    } else {
        note += &format!(
            "/// @dev The permutation is split into {parts} contracts, deployed last to first by DeployParts\n"
        );
        imports = format!(
            "import {{DeployParts}} from \"../{}{}/t{t}/DeployParts.sol\";\n",
            if fork.name == DEFAULT_HARDFORK {
                ""
            } else {
                "../"
            },
            huff_dir(fork)
        );
        let codes: Vec<String> = (0..parts)
            .map(|i| {
                format!(
                    "        initcodes[{i}] = {config}.creation_code(\"{}\");",
                    huff_name(fork, t, &format!("Part{i}"))
                )
            })
            .collect();
        format!(
            "        bytes[] memory initcodes = new bytes[]({parts});
{}
        perm = DeployParts.deploy(initcodes);",
            codes.join("\n")
        )
    };
    let cases = render_vector_cases(t, vectors);
    format!(
        "// SPDX-License-Identifier: MIT
// This file is generated by generator/huff/generate.ts. Do not edit manually.
pragma solidity ^0.8.13;

import {{Test}} from \"forge-std/Test.sol\";
import {{HuffDeployer}} from \"foundry-huff/HuffDeployer.sol\";
{imports}
/// @notice Vectors come from the BigInt reference permutation in generator/shared/reference.ts
{note}contract {name}Test is Test {{
    uint256 constant PRIME = {prime};

    address private perm;

    function setUp() public {{
{set_up}
    }}

    function _permute(uint256[{t}] memory input) internal view returns (uint256[{t}] memory out) {{
        (bool ok, bytes memory ret) = perm.staticcall(abi.encode(input));
        require(ok, \"permutation call failed\");
        out = abi.decode(ret, (uint256[{t}]));
    }}

    function assertEq(uint256[{t}] memory a, uint256[{t}] memory b, string memory err) internal pure {{
        for (uint256 i = 0; i < {t}; i++) {{
            assertEq(a[i], b[i], err);
        }}
    }}
{cases}

    /// @dev inputs at or above PRIME are reduced by the entry contract
    function test_input_sanitization() public view {{
        uint256[{t}] memory a;
        uint256[{t}] memory b;
        for (uint256 i = 0; i < {t}; i++) {{
            a[i] = i + 5;
            b[i] = PRIME + i + 5;
        }}
        assertEq(_permute(a), _permute(b), \"sanitization\");
        for (uint256 i = 0; i < {t}; i++) {{
            a[i] = type(uint256).max % PRIME;
            b[i] = type(uint256).max;
        }}
        assertEq(_permute(a), _permute(b), \"sanitization max\");
    }}
}}
",
        prime = hex(PRIME),
    )
}
