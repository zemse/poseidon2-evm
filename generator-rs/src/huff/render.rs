// Writers for the generated Huff files and the Foundry test of a t != 4
// permutation (huff/render.ts). A permutation that does not fit the fork's
// code size is cut into parts (Part<i>.huff): each part is a contract that
// takes the state as calldata, and every part but the last STATICCALLs the
// next one with the state in memory and returns what it returns.

